-- GTM database: landing-page traffic, on-page behaviour and the companies
-- Snitcher identifies. Written only by server routes holding this project's
-- secret key (the landing's /api/track, admin's Snitcher webhook) and read
-- only by the admin GTM page, so RLS is on with no policies: the anon and
-- authenticated roles see nothing.

-- Companies Snitcher has identified, one row per Snitcher organisation.
create table public.companies (
  id uuid primary key default gen_random_uuid(),
  snitcher_uuid text not null unique,
  name text,
  domain text,
  industry text,
  employee_range text,
  -- The company's headquarters, as Snitcher reports it (not where the visitor browsed from).
  hq_city text,
  hq_state text,
  hq_country text,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  raw jsonb
);

-- One anonymous browser, keyed by the id the tracker keeps in localStorage.
create table public.visitors (
  id uuid primary key,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  visit_count integer not null default 1 check (visit_count >= 0),
  company_id uuid references public.companies (id) on delete set null
);

-- One visit, keyed by the id the tracker keeps in sessionStorage. Updated as
-- the visit goes on (engaged time, max scroll, last event).
create table public.sessions (
  id uuid primary key,
  visitor_id uuid not null references public.visitors (id) on delete cascade,
  started_at timestamptz not null default now(),
  last_event_at timestamptz not null default now(),
  ended_at timestamptz,
  entry_path text not null,
  referrer text,
  -- Where the visit came from: a utm_source, else the referrer's kind (search, social, direct, ...).
  source text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  utm_term text,
  utm_content text,
  device text check (device in ('desktop', 'tablet', 'mobile')),
  user_agent text,
  viewport_w integer check (viewport_w > 0),
  viewport_h integer check (viewport_h > 0),
  -- Where the visitor browsed from, from Vercel's request headers (city-level,
  -- not the device's position). The GTM map places the visitor's dot here.
  country text,
  state text,
  city text,
  latitude double precision check (latitude between -90 and 90),
  longitude double precision check (longitude between -180 and 180),
  -- Focused, visible and active time only, not wall-clock.
  engaged_ms bigint not null default 0 check (engaged_ms >= 0),
  max_scroll_pct smallint not null default 0 check (max_scroll_pct between 0 and 100)
);

-- Everything that happens on the page. The id is generated by the tracker,
-- so a batch that is resent after a failed beacon inserts nothing twice.
create table public.events (
  id uuid primary key,
  session_id uuid not null references public.sessions (id) on delete cascade,
  occurred_at timestamptz not null,
  type text not null check (type in ('pageview', 'scroll_milestone', 'click', 'rage_click', 'dead_click', 'hover')),
  path text not null,
  -- Scroll milestones: 25, 50, 75, 90 or 100.
  scroll_pct smallint check (scroll_pct in (25, 50, 75, 90, 100)),
  -- Clicks and hovers: position as % of the document, not pixels.
  x_pct numeric(5, 2) check (x_pct between 0 and 100),
  y_pct numeric(5, 2) check (y_pct between 0 and 100),
  el_tag text,
  el_id text,
  el_class text,
  -- First 80 characters of the element's visible text; never form input values.
  el_text text,
  hover_ms integer check (hover_ms >= 0),
  data jsonb,
  constraint scroll_milestone_has_pct check ((type = 'scroll_milestone') = (scroll_pct is not null))
);

-- Each milestone fires once per page per visit.
create unique index events_scroll_milestone_once
  on public.events (session_id, path, scroll_pct)
  where type = 'scroll_milestone';

-- One play of one demo on one page (the same demo plays on the home page and
-- on its product page). `view_number` counts plays of that demo on that page
-- within the visit (1, 2, ...); the tracker upserts the row as the play advances.
create table public.demo_views (
  id bigint generated always as identity primary key,
  session_id uuid not null references public.sessions (id) on delete cascade,
  path text not null,
  demo text not null,
  view_number integer not null check (view_number >= 1),
  started_at timestamptz not null,
  -- Furthest point reached as % of the demo's steps; null for a demo that has
  -- no steps (a still screen), so it never drags an average down.
  max_progress_pct smallint check (max_progress_pct between 0 and 100),
  completed boolean not null default false,
  watched_ms bigint not null default 0 check (watched_ms >= 0),
  unique (session_id, path, demo, view_number)
);

-- Snitcher webhook deliveries, one row per Snitcher session. Snitcher retries
-- failed deliveries up to five times; the primary key keeps a retry from
-- landing twice.
create table public.snitcher_sessions (
  snitcher_session_uuid text primary key,
  company_id uuid references public.companies (id) on delete set null,
  -- Our own session, when the tracker handed its id to Snitcher.
  session_id uuid references public.sessions (id) on delete set null,
  event text not null,
  started_at timestamptz,
  pages_viewed integer check (pages_viewed >= 0),
  referrer text,
  -- The visitor's location for this session, from Snitcher's REST API after
  -- the delivery lands (the webhook itself carries no coordinates). Empty
  -- until fetched; location_fetched_at says when it was.
  city text,
  state text,
  country text,
  latitude double precision check (latitude between -90 and 90),
  longitude double precision check (longitude between -180 and 180),
  location_fetched_at timestamptz,
  received_at timestamptz not null default now(),
  raw jsonb not null
);

-- The Landing tab reads by date range; the drill-downs read by session and company.
create index sessions_started_at on public.sessions (started_at desc);
create index sessions_visitor on public.sessions (visitor_id);
create index sessions_state on public.sessions (state);
create index events_session_time on public.events (session_id, occurred_at);
create index events_type_time on public.events (type, occurred_at desc);
create index demo_views_demo_time on public.demo_views (demo, started_at desc);
create index demo_views_session on public.demo_views (session_id);
create index visitors_company on public.visitors (company_id);
create index companies_last_seen on public.companies (last_seen_at desc);
create index snitcher_sessions_company_time on public.snitcher_sessions (company_id, started_at desc);
create index snitcher_sessions_session on public.snitcher_sessions (session_id);
-- The sweep that retries rows whose location fetch failed.
create index snitcher_sessions_location_pending on public.snitcher_sessions (received_at)
  where location_fetched_at is null;

alter table public.companies enable row level security;
alter table public.visitors enable row level security;
alter table public.sessions enable row level security;
alter table public.events enable row level security;
alter table public.demo_views enable row level security;
alter table public.snitcher_sessions enable row level security;

revoke all on public.companies, public.visitors, public.sessions, public.events, public.demo_views, public.snitcher_sessions
  from anon, authenticated;


-- One tracker batch from the landing's /api/track, applied in one transaction:
-- the visitor and the visit upserted, the events inserted once each (their ids
-- are the tracker's, so a resent batch adds nothing), the demo plays merged by
-- keeping the furthest progress and the longest watch. Engaged time and max
-- scroll arrive as running totals, so the larger value always wins.
--
-- `p` = { visitor_id, session: {...}, geo: {...}, events: [...], demo_views: [...] }
create function public.gtm_ingest(p jsonb)
returns void
language plpgsql
set search_path = public
as $$
declare
  s jsonb := p -> 'session';
  g jsonb := coalesce(p -> 'geo', '{}'::jsonb);
  v_id uuid := (p ->> 'visitor_id')::uuid;
  s_id uuid := (s ->> 'id')::uuid;
  seen timestamptz := coalesce((s ->> 'last_event_at')::timestamptz, now());
  is_new boolean;
begin
  insert into visitors (id, first_seen_at, last_seen_at, visit_count)
  values (v_id, coalesce((s ->> 'started_at')::timestamptz, seen), seen, 0)
  on conflict (id) do update set last_seen_at = greatest(visitors.last_seen_at, excluded.last_seen_at);

  insert into sessions (
    id, visitor_id, started_at, last_event_at, ended_at, entry_path, referrer, source,
    utm_source, utm_medium, utm_campaign, utm_term, utm_content,
    device, user_agent, viewport_w, viewport_h,
    country, state, city, latitude, longitude,
    engaged_ms, max_scroll_pct
  ) values (
    s_id, v_id, coalesce((s ->> 'started_at')::timestamptz, seen), seen, (s ->> 'ended_at')::timestamptz,
    coalesce(s ->> 'entry_path', '/'), s ->> 'referrer', s ->> 'source',
    s ->> 'utm_source', s ->> 'utm_medium', s ->> 'utm_campaign', s ->> 'utm_term', s ->> 'utm_content',
    s ->> 'device', s ->> 'user_agent', (s ->> 'viewport_w')::integer, (s ->> 'viewport_h')::integer,
    g ->> 'country', g ->> 'state', g ->> 'city', (g ->> 'latitude')::double precision, (g ->> 'longitude')::double precision,
    coalesce((s ->> 'engaged_ms')::bigint, 0), coalesce((s ->> 'max_scroll_pct')::smallint, 0)
  )
  on conflict (id) do nothing
  returning true into is_new;

  if is_new then
    update visitors set visit_count = visit_count + 1 where id = v_id;
  else
    update sessions set
      last_event_at = greatest(last_event_at, seen),
      ended_at = coalesce((s ->> 'ended_at')::timestamptz, ended_at),
      engaged_ms = greatest(engaged_ms, coalesce((s ->> 'engaged_ms')::bigint, 0)),
      max_scroll_pct = greatest(max_scroll_pct, coalesce((s ->> 'max_scroll_pct')::smallint, 0)),
      -- A later batch can carry the location the first one lacked.
      country = coalesce(country, g ->> 'country'),
      state = coalesce(state, g ->> 'state'),
      city = coalesce(city, g ->> 'city'),
      latitude = coalesce(latitude, (g ->> 'latitude')::double precision),
      longitude = coalesce(longitude, (g ->> 'longitude')::double precision)
    where id = s_id and visitor_id = v_id;
  end if;

  insert into events (id, session_id, occurred_at, type, path, scroll_pct, x_pct, y_pct, el_tag, el_id, el_class, el_text, hover_ms, data)
  select e.id, s_id, e.occurred_at, e.type, e.path, e.scroll_pct, e.x_pct, e.y_pct, e.el_tag, e.el_id, e.el_class, e.el_text, e.hover_ms, e.data
  from jsonb_to_recordset(coalesce(p -> 'events', '[]'::jsonb)) as e(
    id uuid, occurred_at timestamptz, type text, path text, scroll_pct smallint,
    x_pct numeric, y_pct numeric, el_tag text, el_id text, el_class text, el_text text, hover_ms integer, data jsonb
  )
  on conflict do nothing;

  insert into demo_views (session_id, path, demo, view_number, started_at, max_progress_pct, completed, watched_ms)
  select s_id, coalesce(d.path, '/'), d.demo, d.view_number, d.started_at, d.max_progress_pct, coalesce(d.completed, false), coalesce(d.watched_ms, 0)
  from jsonb_to_recordset(coalesce(p -> 'demo_views', '[]'::jsonb)) as d(
    path text, demo text, view_number integer, started_at timestamptz, max_progress_pct smallint, completed boolean, watched_ms bigint
  )
  on conflict (session_id, path, demo, view_number) do update set
    max_progress_pct = greatest(demo_views.max_progress_pct, excluded.max_progress_pct),
    completed = demo_views.completed or excluded.completed,
    watched_ms = greatest(demo_views.watched_ms, excluded.watched_ms);
end;
$$;

revoke all on function public.gtm_ingest(jsonb) from public, anon, authenticated;
grant execute on function public.gtm_ingest(jsonb) to service_role;
